/**
 * 出口诚实闸（2026-09-05 前后台架构）——承诺-动作一致性校验。
 *
 * 根源修法：写动作最伤信任的失败模式是前台空口答应「已设置/已订好」但什么都没做。
 * 旧架构在**入口**用词法网猜「这是不是写动作」（L0.5），词表永远打地鼠；
 * 本闸改在**出口**校验「说的和做的是否一致」：前台回复含完成承诺话术、
 * 但本轮既没派发任务也没执行任何工具 → 自动补派后台任务把承诺变成真。
 *
 * 与 L0.5 的本质区别：这是对「声称完成」这一行为本身的契约校验（话题无关、
 * 不枚举任务类型），而不是对话题词的猜测；且误伤代价为零——补派的只是把
 * 前台已经说出口的承诺真正落实，后台完成结果会回灌对话确认。
 */

/**
 * 完成承诺话术：现在时/完成时的「已办妥」类断言 + 即时承诺的「这就去办」类断言。
 * 只锚定动作语义（设置/创建/订/买/提交…）+ 完成体标记（好/了/成功/已经），
 * 不锚定话题词；裸动词（如"要订几点"）不命中。
 */
const COMMITMENT_CLAIM_RE =
  /(?:设置|创建|建立|添加|加入|安排|预订|预定|下单|提交|保存|删除|取消|写入)(?:好|好啦|好了|成功|完成|上去了?|进去了?)|(?:已经?|刚)(?:帮你|替你|给您|给你)?(?:设置|创建|订|买|提交|加入|安排|保存|删除|取消|办|记)|帮(?:你|您)?(?:设置|订|买|创建|安排|提交|办|记)(?:好|好啦|好了)|记下(?:了|好)|记好|设好|订好|买好|建好|加好|写好|办妥|搞定了?|处理好了?|查好了?|安排上了?|(?:在办了?|正在办|这就去?(?:订|设置|创建|安排|处理|办|买|查|提交|下单|弄)|马上(?:帮你|去)?(?:订|设置|创建|安排|处理|办|买|查|提交|下单)|这就帮你弄)/;

/** 否定/未然语境：声称没做、还没做、做不了的话术不算承诺。 */
const COMMITMENT_EXCLUDE_RE =
  /还没|尚未|没有(?:设置|创建|订|买|办|查)|无法|不能|办不了|做不到|失败了?|没能|稍后(?:再|会)|等(?:我|一下)|不确定/;

/**
 * 判断前台回复是否含「已办妥」类承诺话术（供出口闸决定是否补派）。
 * 仅供 fast 前台路径使用；任务面结果不校验（任务面本身就在真执行）。
 */
export function hasCommitmentClaim(text: string): boolean {
  const t = (text ?? "").trim();
  if (!t || t.length > 2000) return false;
  if (COMMITMENT_EXCLUDE_RE.test(t)) return false;
  return COMMITMENT_CLAIM_RE.test(t);
}
